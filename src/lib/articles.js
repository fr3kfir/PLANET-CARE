// One short practical line per day, from the articles' bullet points.
export function tipOfTheDay(date = new Date()) {
  const lines = ARTICLES.flatMap(a => a.sections.flatMap(s => (s.list || []).map(text => ({ text, article: a }))))
  const day = Math.floor(date.getTime() / 86_400_000)
  return lines[day % lines.length]
}
